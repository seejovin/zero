import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { loadHostingManifest } from "./hosting-manifest.mjs";

const root = new URL("../", import.meta.url);
const version = JSON.parse(await readFile(new URL("package.json", root), "utf8")).version;
const source = await readFile(new URL("dist/server/index.js", root), "utf8");
const manifest = JSON.parse(await readFile(new URL("dist/.openai/hosting.json", root), "utf8"));
const selected = await loadHostingManifest(fileURLToPath(root));
assert.deepEqual(manifest, selected.manifest);
assert.equal(manifest.static, undefined);
const module = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
assert.equal(typeof module.default?.fetch, "function");
const request = (path, method = "GET") => module.default.fetch(new Request(`https://wallet.example${path}`, { method }));
const index = await request("/");
assert.equal(index.status, 200);
assert.equal(index.headers.get("Cache-Control"), "no-store");
assert.ok(index.headers.get("Content-Security-Policy").includes("frame-ancestors 'none'"));
const html = await index.text();
assert.ok(html.includes('<meta name="wallet-rpc-relay" content="/api/rpc">'));
assert.ok(!html.includes("INTERFACE REVIEW"));
let integrityChecks = 0;
const diagnostics = await request("/diagnostics.html");
assert.equal(diagnostics.status, 200);
const diagnosticHtml = await diagnostics.text();
assert.ok(diagnosticHtml.includes('<meta name="wallet-rpc-relay" content="/api/rpc">'));
for (const tag of (html + diagnosticHtml).matchAll(/<(?:script|link)\b[^>]*>/g)) {
  const integrity = /integrity="sha384-([^"]+)"/.exec(tag[0]);
  const asset = /(?:src|href)="([^"]+)"/.exec(tag[0]);
  if (!integrity || !asset) continue;
  const response = await request(`/${asset[1].replace(/^\//, "")}`);
  assert.equal(response.status, 200);
  assert.equal(createHash("sha384").update(Buffer.from(await response.arrayBuffer())).digest("base64"), integrity[1]);
  integrityChecks++;
}
assert.ok(integrityChecks >= 4);
const wasm = await request("/crypto/wallet_core_bg.wasm");
assert.equal(wasm.headers.get("Content-Type"), "application/wasm");
const bytes = await wasm.arrayBuffer();
assert.ok(WebAssembly.validate(bytes));
assert.equal((await request("/dev/preview.js")).status, 404);
assert.equal((await request("/api/rpc")).status, 405);
assert.equal((await request("/", "POST")).status, 405);
assert.deepEqual(await (await request("/api/health")).json(), { version, relay: true, networks: [1, 8453] });
const candidates = await (await request("/api/activity?chainId=8453&address=0x1111111111111111111111111111111111111111")).json();
assert.equal(candidates.partial, true);
assert.deepEqual(candidates.hashes, []);
const result = { time: new Date().toISOString(), result: "passed", version, hosting_manifest_preserved: true, hosting_mode: selected.mode, valid_esm_fetch: true, embedded_wasm_valid: true, sri_assets_verified: integrityChecks, hosted_relay_meta: true, strict_headers: true, preview_excluded: true, bundle_bytes: Buffer.byteLength(source), wasm_sha256: createHash("sha256").update(Buffer.from(bytes)).digest("hex") };
await mkdir(new URL("build/verification/", root), { recursive: true });
await writeFile(new URL(`build/verification/hosted-artifact-v${version.replaceAll(".", "")}.json`, root), JSON.stringify(result, null, 2) + "\n");
console.log(JSON.stringify(result));
